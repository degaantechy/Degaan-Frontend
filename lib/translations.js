export function getLocalizedPropertyField(property, field, language) {
  if (!property) return ''
  if (language === 'so') {
    return property[`${field}_so`] || property[field] || ''
  }
  return property[field] || ''
}

export function getPropertyStatus(status, language) {
  const normalized = String(status || '').toLowerCase().replace(/[_\s-]+/g, '-')
  const key = normalized === 'under-construction' ? 'construction' : normalized
  return translations[language]?.property?.status?.[key] || status || ''
}

export function getPropertyType(type, language) {
  const key = String(type || '').toLowerCase().replace(/[_\s-]+/g, '-')
  return translations[language]?.property?.types?.[key] || type || ''
}
